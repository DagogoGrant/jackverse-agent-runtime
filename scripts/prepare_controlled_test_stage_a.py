    print(f"Timestamp: {dossier['timestamp']}")
    print(f"Status:    {dossier['status']}")
    print("=" * 80)
    print()
    print("[1] RUNTIME & SAFETY BOUNDARIES")
    print(f"  Operator ID:                     {dossier['operator_id']}")
    print(f"  Connected Google Account:        {dossier['sender_email']}")
