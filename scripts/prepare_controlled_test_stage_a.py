def verify_runtime_safety(db_path: str, operator_id: str = "operator-1") -> dict[str, Any]:
    """Verify fail-closed execution flags and authentic Google OAuth connection."""
    # 1. Execution flags
    real_exec = os.getenv("CASEWORKER_REAL_EXECUTION_ENABLED", "false").lower() in ("true", "1", "yes")
    gmail_exec = os.getenv("CASEWORKER_GMAIL_EXECUTION_ENABLED", "false").lower() in ("true", "1", "yes")
    if real_exec or gmail_exec:
        raise RuntimeError(
            f"SAFETY VIOLATION: Live execution flags must be disabled! "
            f"CASEWORKER_REAL_EXECUTION_ENABLED={real_exec}, CASEWORKER_GMAIL_EXECUTION_ENABLED={gmail_exec}"
        )

    # 2. Check credentials in DB
    if not os.path.exists(db_path):
        raise FileNotFoundError(f"Database file does not exist at {db_path}")

    conn = sqlite3.connect(db_path, timeout=5.0)
    cur = conn.cursor()
    table_name = "user_oauth_credentials"
    tables = [r[0] for r in cur.execute("SELECT name FROM sqlite_master WHERE type='table'").fetchall()]
    if "user_oauth_credentials" in tables:
        table_name = "user_oauth_credentials"
    elif "oauth_credentials" in tables:
        table_name = "oauth_credentials"
    else:
        conn.close()
        raise RuntimeError(f"No OAuth credentials table found in {db_path}")

    row = cur.execute(
        f"SELECT user_id, provider, authenticated_email, scopes, access_token_enc FROM {table_name} WHERE user_id = ? AND provider = 'gmail'",
        (operator_id,),
    ).fetchone()
    conn.close()

    if row is None:
        raise RuntimeError(f"No OAuth credentials found for user '{operator_id}' and provider 'gmail' in {db_path}")

    user_id, provider, auth_email, scopes_str, access_token_enc = row
    scopes = scopes_str.split() if isinstance(scopes_str, str) else list(scopes_str or [])
    gmail_send_scope = "https://www.googleapis.com/auth/gmail.send"
    if gmail_send_scope not in scopes:
        raise RuntimeError(f"Required scope '{gmail_send_scope}' not granted. Scopes: {scopes}")

    # 3. Verify encryption key can decrypt without exposing plaintext
    enc_key = os.getenv("CASEWORKER_ENCRYPTION_KEY", "")
    if len(enc_key) < 32:
        raise RuntimeError("CASEWORKER_ENCRYPTION_KEY is missing or shorter than 32 characters.")

    cipher = TokenCipher(primary_key=enc_key)
    try:
        decrypted = cipher.decrypt(access_token_enc)
        if not decrypted:
            raise ValueError("Decrypted token is empty.")
    except Exception as exc:
        raise RuntimeError(f"Failed to decrypt stored OAuth token: {exc}")

    return {
        "operator_id": user_id,
        "provider": provider,
        "authenticated_email": auth_email,
        "scopes": scopes,
        "cipher_verified": True,
        "real_execution_flags_disabled": True,
    }


def prepare_stage_a(
    db_path: str,
    operator_id: str = "operator-1",
    recipient_email: str | None = None,
) -> dict[str, Any]:
    """Execute Stage A: establish test identity, harmless artifacts, and freeze package with PENDING approval."""
    safety_info = verify_runtime_safety(db_path, operator_id=operator_id)
    sender_email = safety_info["authenticated_email"]
    target_recipient = recipient_email or sender_email

    storage = SQLiteCaseworkerStorage(db_path=db_path)
    package_service = PackageService(storage)

    opp_id = f"opp-controlled-test-5332"
    case_id = f"case-controlled-test-5332"
    art_set_id = f"set-controlled-test-5332"

    with storage.unit_of_work() as uow:
        # 1. Existing or new Case (saved before Opportunity due to converted_case_id FK)
        case = uow.cases.get_by_id(case_id)
        if case is None:
            case = Case(
                case_id=case_id,
                user_id=operator_id,
                title="[JACKVERSE INTERNAL TEST] Governed Gmail Transmission Verification",
                goal="Verify governed Gmail transmission workflow under strict human authorization boundaries",
                case_type=CaseType.JOB_APPLICATION,
                status=CaseStatus.PLANNING,
            )
            uow.cases.save(case)

        # 2. Existing or new Opportunity
        opp = uow.opportunities.get_by_id(opp_id)
        if opp is None:
            opp = Opportunity(
                opportunity_id=opp_id,
                user_id=operator_id,
                opportunity_type=OpportunityType.JOB,
                title="[JACKVERSE INTERNAL TEST] Governed Gmail Transmission Verification",
                organization="JackVerse Verification Lab",
                source_url="https://localhost:3443/verification/controlled-test",
                source_name="operator_internal_test",
                requirements=["Reliable email delivery", "Cryptographic receipt binding"],
                metadata={
                    "is_internal_test": True,
                    "test_purpose": "Phase 5.3.3.2 Controlled Live Transmission Acceptance",
                    "application_channel": "email",
                    "application_email": target_recipient,
                    "accepts_email_applications": True,
                    "email_subject": EXACT_PROPOSED_SUBJECT,
                },
                converted_case_id=case_id,
                status=OpportunityStatus.SHORTLISTED,
            )
            uow.opportunities.save(opp)

        # 3. Context Facts
        fact_email_id = f"fact-email-{operator_id}"
        fact_email = uow.context.get_by_id(fact_email_id)
        if fact_email is None:
            fact_email = ContextFact(
                fact_id=fact_email_id,
                user_id=operator_id,
                namespace="identity",
                key="email",
                value=sender_email,
                verification_status=VerificationStatus.USER_VERIFIED,
                allowed_purposes=["job_application", "case_preparation", "test_verification"],
            )
            uow.context.save(fact_email)

        fact_name_id = f"fact-name-{operator_id}"
        fact_name = uow.context.get_by_id(fact_name_id)
        if fact_name is None:
            fact_name = ContextFact(
                fact_id=fact_name_id,
                user_id=operator_id,
                namespace="identity",
                key="full_name",
                value="Candidate Test Subject",
                verification_status=VerificationStatus.USER_VERIFIED,
                allowed_purposes=["job_application", "case_preparation", "test_verification"],
            )
            uow.context.save(fact_name)

        # 4. Preparation Report
        analyzer = PreparationAnalyzer()
        report = uow.preparation_reports.get_latest_for_case(case_id)
        if report is None:
            report = analyzer.analyze(
                case=case,
                opportunity=opp,
                granted_facts=[fact_email, fact_name],
                denied_descriptors=[],
            )
            uow.preparation_reports.save(report)

        # 5. Grounded Claim
        supp_hash = compute_support_snapshot_hash([fact_name])
        claim_id = f"claim-test-{operator_id}"
        claim = uow.claims.get_by_id(claim_id)
        if claim is None:
            claim = Claim(
                claim_id=claim_id,
                user_id=operator_id,
                purpose="test_verification",
                text="Authorized operator conducting controlled Gmail integration test.",
                status=ClaimStatus.SUPPORTED,
                supporting_fact_ids=[fact_name.fact_id],
                case_id=case_id,
                source_report_id=report.report_id,
                source_claim_intent_id="intent-test-1",
                assertion_schema="test_authorization",
                assertion_json=f'{{"kind": "test_auth", "fact_ids": ["{fact_name.fact_id}"]}}',
                support_snapshot_hash=supp_hash,
                version=1,
            )
            uow.claims.save(claim)

        # 6. Harmless Prepared Artifacts
        # 6a. Cover Letter (contains exact prompt body)
        cl_grounding = compute_artifact_grounding_hash(claims=[], direct_facts=[fact_name])
        art_cl_id = f"art-cl-{case_id}"
        existing_cl = uow.preparation_artifacts.get_by_id(art_cl_id)
        if existing_cl is None:
            art_cl = PreparedArtifact(
                artifact_id=art_cl_id,
                artifact_set_id=art_set_id,
                case_id=case_id,
                opportunity_id=opp_id,
                user_id=operator_id,
                material_type=PreparationMaterialType.COVER_LETTER,
                title="Cover Letter (Controlled Test Message)",
                planner_version=PLANNER_VERSION,
                status=ArtifactStatus.DRAFT,
                source_report_id=report.report_id,
                grounding_snapshot_hash=cl_grounding,
                blocks=[
                    ArtifactBlock(
                        block_id="b-cl-body",
                        content=EXACT_PROPOSED_BODY,
                        grounding_type=ArtifactGroundingType.CONTEXT_FACT,
                        fact_ids=[fact_name.fact_id],
                    )
                ],
            )
            uow.preparation_artifacts.save(art_cl)
        else:
            art_cl = existing_cl

        # 6b. Harmless Synthetic CV
        cv_grounding = compute_artifact_grounding_hash(claims=[claim], direct_facts=[fact_name])
        art_cv_id = f"art-cv-{case_id}"
        existing_cv = uow.preparation_artifacts.get_by_id(art_cv_id)
        if existing_cv is None:
            art_cv = PreparedArtifact(
                artifact_id=art_cv_id,
                artifact_set_id=art_set_id,
                case_id=case_id,
                opportunity_id=opp_id,
                user_id=operator_id,
                material_type=PreparationMaterialType.CV,
                title="Synthetic Verification Document (No Personal Data)",
                planner_version=PLANNER_VERSION,
                status=ArtifactStatus.DRAFT,
                source_report_id=report.report_id,
                grounding_snapshot_hash=cv_grounding,
                blocks=[
                    ArtifactBlock(
                        block_id="b-cv-head",
                        block_type="header",
                        content="Test Verification Asset",
                        grounding_type=ArtifactGroundingType.CONTEXT_FACT,
                        fact_ids=[fact_name.fact_id],
                    ),
                    ArtifactBlock(
                        block_id="b-cv-body",
                        content="Synthetic payload for Phase 5.3.3.2 controlled transmission test. Zero personal application information.",
                        grounding_type=ArtifactGroundingType.CLAIM,
                        claim_ids=[claim.claim_id],
                    ),
                ],
            )
            uow.preparation_artifacts.save(art_cv)
        else:
            art_cv = existing_cv

        # 6c. Screening Q&A
        qa_grounding = compute_artifact_grounding_hash(claims=[claim], direct_facts=[])
        art_qa_id = f"art-qa-{case_id}"
        existing_qa = uow.preparation_artifacts.get_by_id(art_qa_id)
        if existing_qa is None:
            art_qa = PreparedArtifact(
                artifact_id=art_qa_id,
                artifact_set_id=art_set_id,
                case_id=case_id,
                opportunity_id=opp_id,
                user_id=operator_id,
                material_type=PreparationMaterialType.SCREENING_ANSWERS,
                title="Screening Q&A (Controlled Test)",
                planner_version=PLANNER_VERSION,
                status=ArtifactStatus.DRAFT,
                source_report_id=report.report_id,
                grounding_snapshot_hash=qa_grounding,
                blocks=[
                    ArtifactBlock(
                        block_id="b-qa-1",
                        block_type="qna_item",
                        content="### Q: Verification Purpose?\n\nPhase 5.3.3.2 Controlled Test.",
                        grounding_type=ArtifactGroundingType.CLAIM,
                        claim_ids=[claim.claim_id],
                        metadata={
                            "question": "Verification Purpose?",
                            "answer": "Phase 5.3.3.2 Controlled Test.",
                            "answer_status": "ANSWERED",
                        },
                    )
                ],
            )
            uow.preparation_artifacts.save(art_qa)
        else:
            art_qa = existing_qa

    # 7. Check or Freeze PreparationPackage using PackageService
    bundle = package_service.get_existing_package_bundle(
        user_id=operator_id,
        case_id=case_id,
        artifact_set_id=art_set_id,
    )
    if bundle is not None:
        package, action, approval, findings, refreshed_case = bundle
    else:
        package, action, approval, findings, refreshed_case = package_service.verify_and_prepare_package(
            user_id=operator_id,
            case_id=case_id,
            artifact_set_id=art_set_id,
        )

    # 8. VERIFY STAGE A INVARIANTS: STOP BEFORE HUMAN APPROVAL
    if approval.status != ApprovalStatus.PENDING:
        print(f"Note: Existing package approval status is {approval.status.value}")

    # Compute artifact rendered hashes
    cv_rendered = art_cv.compute_rendered_payload()
    cv_hash = compute_sha256(cv_rendered)
    cl_rendered = art_cl.compute_rendered_payload()
    cl_hash = compute_sha256(cl_rendered)

    dossier = {
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "stage": "STAGE_A_CONTENT_PREPARATION",
        "status": "AWAITING_HUMAN_CONTENT_APPROVAL",
        "safety_checks": safety_info,
        "operator_id": operator_id,
        "sender_email": sender_email,
        "recipient_email": target_recipient,
        "opportunity": {
            "opportunity_id": opp_id,
            "title": opp.title,
            "organization": opp.organization,
            "is_internal_test": True,
        },
        "case": {
            "case_id": case_id,
            "title": refreshed_case.title,
            "status": refreshed_case.status.value,
        },
        "preparation_package": {
            "package_id": package.package_id,
            "status": package.status.value,
            "package_fingerprint": package.package_fingerprint,
            "findings_count": len(findings),
            "findings": findings,
        },
        "approval": {
            "approval_id": approval.approval_id,
            "action_id": action.action_id,
            "action_type": action.action_type.value,
            "status": approval.status.value,
            "requires_human_decision": True,
        },
        "proposed_message": {
            "subject": EXACT_PROPOSED_SUBJECT,
            "body": EXACT_PROPOSED_BODY,
            "test_identifier": STABLE_TEST_ID,
            "body_sha256": cl_hash,
        },
        "proposed_attachments": [
            {
                "filename": f"cv_{operator_id.replace('-', '_')}.txt",
                "role": "cv",
                "content_preview": cv_rendered,
                "content_sha256": cv_hash,
                "byte_size": len(cv_rendered.encode("utf-8")),
            }
        ],
        "zero_real_transmissions": True,
        "human_send_authorization": "NOT_GRANTED",
    }
    return dossier


def main() -> int:
    parser = argparse.ArgumentParser(description="JackVerse Phase 5.3.3.2 Stage A Preparation")
    parser.add_argument(
        "--db-path",
        default=os.getenv("CASEWORKER_DB_PATH", "/app/.caseworker/caseworker.db"),
        help="Path to Caseworker SQLite database",
    )
    parser.add_argument("--operator-id", default="operator-1", help="Operator ID")
    parser.add_argument("--recipient-email", default=None, help="Recipient email (defaults to operator's email)")
    parser.add_argument("--json", action="store_true", help="Output JSON only")
    args = parser.parse_args()

    try:
        dossier = prepare_stage_a(
            db_path=args.db_path,
            operator_id=args.operator_id,
            recipient_email=args.recipient_email,
        )
    except Exception as exc:
        print(f"STAGE A PREPARATION FAILED: {exc}", file=sys.stderr)
        return 1

